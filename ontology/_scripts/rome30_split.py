END_PAGE = 317      # 옮기고 나서
CHRONO_PAGE = 322   # 로마사 연표

# 컬럼 인덱스 = 책페이지 + 2 (오차 ±1). 앞뒤로 1컬럼씩 여유를 둬 오프바이원을 흡수한다.
COL_OFFSET = 2
SLACK = 1

# 앞뒤 부속물. 여기는 책페이지 대신 컬럼 인덱스를 직접 쓴다 — 앞부분은 쪽번호가
# 무번호·별도 체계라 book page → column 변환(COL_OFFSET)이 성립하지 않는다.
# 지도(col 8~9)는 저작권 자료라 뽑지 않는다. visual/ 참조.
EXTRA = [
    ("front_일러두기.txt", 6, 8, "일러두기"),
    ("front_책머리에.txt", 10, 17, "책머리에"),
    ("back_옮기고_나서.txt", 319, 324, "옮기고 나서"),
]

norm = lambda s: re.sub(r"[\s'\"`·•,.\-_「」『』]", "", s)


def columns(doc):
    """PDF 1장 = 책 2페이지 펼침. bbox 중심 x로 좌/우를 갈라 평탄한 컬럼 리스트로."""
    out = []
    for page in doc:
        mid = page.rect.width / 2
        blocks = page.get_text("blocks")
        for left in (True, False):
            col = sorted([b for b in blocks if ((b[0] + b[2]) / 2 < mid) == left],
                         key=lambda b: b[1])
            out.append("\n".join(b[4].rstrip() for b in col))
    return out


def main(write):
    doc = fitz.open(SRC)
    cols = columns(doc)
    starts = [t[0] for t in TOC] + [END_PAGE]

    segments = []
    for i, (page, title, subtitle, subs) in enumerate(TOC):
        lo = max(0, page + COL_OFFSET - SLACK)
        hi = min(len(cols), starts[i + 1] + COL_OFFSET + SLACK)
        segments.append((f"point_{i+1:02d}.txt", lo, hi, title, subtitle, subs))
    # 연표는 앞쪽 SLACK을 주지 않는다 — 주면 「옮기고 나서」 꼬리가 딸려 들어온다.
    segments.append(("chronology.txt", CHRONO_PAGE + COL_OFFSET, len(cols),
                     "로마사 연표", "", []))
    segments += [(f, lo, hi, t, "", []) for f, lo, hi, t in EXTRA]

    failures, warnings = [], []
    for fname, lo, hi, title, subtitle, subs in segments:
        body = "\n".join(cols[lo:hi])
        nb = norm(body)
        # 표지 제목은 OCR이 자주 깨진다(15·24번). 본문에 박힌 소절 제목으로 경계를 검증한다.
        # OCR 변형(흑독한/혹독한 등)으로 개별 소절은 놓칠 수 있다. 과반이 잡히면 경계는 맞다.
        missing = [s.split("|")[0] for s in subs if norm(s.split("|")[0])[:8] not in nb]
        if subs and len(missing) * 2 > len(subs):
            failures.append(f"{fname}: 소절 {len(missing)}/{len(subs)}개 미검출 — 경계 어긋남 의심")
        elif missing:
            warnings.append(f"{fname}: 소절 {len(missing)}/{len(subs)}개 OCR 변형 — {missing}")
        header = "\n".join([
            f"# {title}" + (f" — {subtitle}" if subtitle else ""),
            f"# 원본: PDF 컬럼 {lo}~{hi-1} (책 페이지 약 {lo-COL_OFFSET}~{hi-COL_OFFSET})",
            "# 소절 (차례 기준, OCR본이 깨졌을 수 있으니 이 목록을 정본으로 삼을 것):",
            *[f"#   - {s.split('|')[0]}  (p{s.split('|')[1]})" for s in subs],
            "#" + "=" * 70, "",
        ])
        print(f"{fname:20s} cols {lo:3d}~{hi-1:3d}  {len(body):6d}자  {title[:30]}")
        if write:
            OUT.mkdir(parents=True, exist_ok=True)
            (OUT / fname).write_text(header + body, encoding="utf-8")

    if warnings:
        print("\n[경고] 소절 제목 일부 OCR 손상 (에이전트가 차례 목록으로 복원):")
        for w in warnings:
            print("  " + w)
    assert len(segments) == 31 + len(EXTRA), \
        f"세그먼트 {31 + len(EXTRA)}개(포인트 30 + 연표 + 부속물)여야 하는데 {len(segments)}개"
    assert not failures, "경계 검증 실패:\n  " + "\n  ".join(failures)
    print(f"\n검증 통과: 포인트 30 + 연표 1 = {len(segments)}개, 모든 포인트의 첫 소절 검출됨")


if __name__ == "__main__":
    main(write="--write" in sys.argv)
