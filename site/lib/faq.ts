/** 이 화면에 딸린 물음만. 경로 접두로 맞춘다 — `/start/install`은 `/start` 것을 받는다 */
export function faqFor(path: string): FaqItem[] {
  return FAQ.filter((f) => f.pages?.some((p) => path === p || path.startsWith(`${p}/`)))
}

export function faqByCategory(): { category: FaqCategory; items: FaqItem[] }[] {
  return FAQ_CATEGORIES.map((category) => ({
    category,
    items: FAQ.filter((f) => f.category === category),
  }))
}
