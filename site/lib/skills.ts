/**
 * 스킬 여덟 벌 — **산문이 아니라 필드로 둔다.**
 *
 * 앞 판은 `content/use/skills.md` 마크다운이었고 반려됐다("가독성이 너무 안 좋다,
 * 사용자적 관점의 UXUI와 라이팅이 되어 있지 않다"). 화면에서 무너진 자리는 셋이었다 —
 * 표 한 칸에 영문 슬러그 다섯이 뭉쳐 **세 줄로 흘렀고**, 「무엇을 하나: …」처럼 라벨이
 * 본문과 같은 줄에 붙은 불릿 넷은 훑을 수가 없었고, **정작 사람이 붙여넣을 「말 거는 법」이
 * 인라인 코드라 복사 버튼이 없었다.**
 *
 * 그래서 스킬을 쪼개 여기 둔다. 화면은 `components/`가 카드로 그린다. 문장 길이 제한
 * (does 50자, output 60자, 둘 다 한 문장)은 장식이 아니라 **카드가 무너지지 않는 한계**다.
 * 사실과 트리거 문구는 전부 위 마크다운과 `.agent/skills/<이름>/SKILL.md`에서 옮긴 것이고,
 * 새로 지어낸 것은 없다. `lib/recipes.ts`의 형제다.
 */

export type SkillTier = 'paste' | 'local' | 'operator'

export type Skill = {
  /** 코드 이름. 화면에서는 작게만 보인다 */
  id: string
  /** 한국어 이름. **이게 제목이다.** 명사형 한 줄 */
  title: string
  tier: SkillTier
  /** 무엇을 하나. **한 문장, 50자 이내** */
  does: string
  /** 무엇을 주면 되나. **한 줄** */
  input: string
  /** 무엇이 나오나. **한 문장, 60자 이내** */
  output: string
  /** AI 창에 그대로 붙여넣을 말. SKILL.md의 트리거 문구 원문 */
  say: string
  /**
   * 이 절차서의 「하지 말 것」 중 **시키는 사람이 알아야 할 한 줄.**
   *
   * 원문 여덟 벌의 「하지 말 것」이 이 절차서들의 존재 이유인데 앞 판에서 카드로
   * 옮기며 통째로 잘려 나갔다. 전부는 못 싣는다 — `.get()`을 쓰라는 식의 구현
   * 얘기는 읽는 사람 것이 아니다. 벌마다 **사람이 시킬 때 달라지는 것 하나**만 옮긴다.
   */
  caution?: string
}

