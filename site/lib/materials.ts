/**
 * AI에게 줄 재료 셋 — **활용하기 전체가 이것 위에 서 있다.**
 *
 * 「무엇을 AI에 주나」와 「우수 사례」가 같은 셋을 각자 손으로 적고 있었다. 사례
 * 화면은 카드 셋을, 재료 화면은 네 칸짜리 표를 그렸는데 같은 것이다. 한쪽만
 * 고치면 두 화면이 어긋나므로 여기 한 벌만 둔다.
 *
 * **`when`이 첫 줄인 이유가 이 파일의 전부다.** 사람이 고르는 기준은 "무엇이
 * 담기나"가 아니라 "지금 내가 뭘 하려는가"다. 크기는 배지로 뺀다 — "이거 창에
 * 들어가나"는 고르기 전에 끝나야 할 물음이다.
 */

export type Material = {
  id: string
  title: string
  /** 그 재료를 집으러 가는 화면 */
  href: string
  /** 언제 쓰나. **고르는 기준이라 카드의 첫 줄이다** */
  when: string
  /** 어디서 어떤 버튼을 누르나 */
  how: string
  /** 무엇이 담기나 */
  holds: string
  /** 크기. 배지로 뜬다 */
  size: string
}

