/**
 * 우수 사례 여덟 건 — **산문이 아니라 필드로 둔다.**
 *
 * 앞 판은 `content/use/recipes.md` 198줄짜리 마크다운이었고 반려됐다("가독성이 너무
 * 안 좋다, 사용자적 관점의 UXUI와 라이팅이 되어 있지 않다"). 원인은 내용이 아니라
 * 형태였다 — **「언제」·「무엇이 나오나」 같은 라벨이 본문과 같은 줄에 굵게 붙어**
 * 한 문단으로 흘러서, 사례 경계가 안 보이고 정작 사람이 찾는 프롬프트 상자가
 * 세 번째 문단에 묻혔다.
 *
 * 그래서 사례를 쪼개 여기 둔다. 화면은 `components/`가 카드로 그린다. 문장 길이
 * 제한(when 40자, result 두 문장, caution 한 문장)은 장식이 아니라 **카드가 무너지지
 * 않는 한계**다 — 늘리려면 화면부터 확인한다. 사실·숫자·프롬프트는 전부 위 마크다운에서
 * 옮긴 것이고, 새로 지어낸 것은 없다.
 */

export type RecipeCategory = '발표 준비' | '인물 확인' | '사실 확인' | '흐름 잡기'

export type Recipe = {
  id: string
  category: RecipeCategory
  /** 사례 이름. 명사형 한 줄 */
  title: string
  /** 언제 쓰나. 한 문장, 40자 이내. "…할 때." 로 끝난다 */
  when: string
  /** 웹 화면만으로 되나, 자료를 컴퓨터에 받아야 되나 */
  needs: 'web' | 'local'
  /** 어디서 무엇을 복사해 오나. 한 줄 */
  material: string
  /** 재료를 가지러 가는 사이트 안 경로 */
  materialHref: string
  /**
   * AI 창에 그대로 붙여넣을 문장. 원문 그대로다.
   *
   * **`scope` 하나는 빈 문자열이다** — 「준비 범위부터 잡기」는 표를 시트에 붙이는 데서
   * 끝나 AI를 아예 안 쓴다. 없는 프롬프트를 지어내지 않았다. `RecipeCard`가 지금은
   * `CodeBlock`을 무조건 그리니 그 카드에 빈 상자가 뜬다 — `{r.prompt ? … : null}`로 뺀다
   */
  prompt: string
  /** 실제로 무엇이 나왔나. 두 문장 이내, 각 60자 이내. 숫자는 살린다 */
  result: string
  /** 조심할 것. 한 문장, 60자 이내 */
  caution?: string
}

